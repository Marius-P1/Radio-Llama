"""Generation jobs: one at a time, progress in memory (D011, D018).

A show is generated by a background task. The steps of an endless show (D044) are plain
blocking calls that wait for the same lock.
"""

import logging
import threading
from pathlib import Path

from radio_llama.api.schemas import Progress
from radio_llama.generator import ShowGenerator, run_generation
from radio_llama.models import Show
from radio_llama.storage import SHOW_FILE, load_show, save_show

log = logging.getLogger(__name__)

RESTARTED_ERROR = "Server restarted during generation."
UNEXPECTED_ERROR = "Unexpected error, see server log."


class StepRefused(Exception):
    """The show cannot take the step that was asked. The message says why (D044)."""


class Jobs:
    """Runs generations one at a time and remembers progress in memory (D011, D018)."""

    def __init__(self, generator: ShowGenerator, output_dir: Path) -> None:
        self._generator = generator
        self._output_dir = output_dir
        self._lock = threading.Lock()
        self._progress: dict[str, Progress] = {}

    def progress(self, show_id: str) -> Progress | None:
        return self._progress.get(show_id)

    def run(self, show: Show) -> None:
        """Generate `show`; a second call waits for the first to finish (one at a time)."""
        try:
            with self._lock:

                def on_progress(done: int, total: int) -> None:
                    self._progress[show.id] = Progress(done=done, total=total)

                try:
                    run_generation(self._generator, show, self._output_dir / show.id, on_progress)
                finally:
                    self._progress.pop(show.id, None)
        except Exception:
            # A bug must never leave a show stuck in "generating" or kill the worker thread.
            log.exception("Show %s crashed", show.id)
            show.status = "failed"
            show.error = UNEXPECTED_ERROR
            save_show(show, self._output_dir / show.id)

    # The steps of an endless show (D044). Unlike `run` they are not background tasks:
    # the request waits for its part. They take the same lock, so one thing is generated
    # at a time (D011), and they write show.json only once a step has succeeded, so a
    # failed step loses nothing and can simply be asked again.

    def extend(self, show_id: str, known: int) -> Show:
        """Add the next break and song to an endless show, unless they are already there.

        `known` is how many segments the caller has. The show is read under the lock:
        when it holds more than that, or is closed, it is returned as it is. So a second
        request for the same part, from a retry or from another tab, waits on the lock
        and then gets the part the first one made, at no cost.
        """
        with self._lock:
            show_dir = self._output_dir / show_id
            show = self._ready_endless_show(show_dir)
            # Before the check of `known`: an `end` can make the show shorter than what a
            # late request knows, and a closed show is returned whatever is asked.
            if not show.is_open:
                return show
            if known > len(show.segments):
                raise StepRefused(f"Show {show_id} has {len(show.segments)} segments, not {known}.")
            if known < len(show.segments):
                return show
            self._generator.extend(show, show_dir)
            save_show(show, show_dir)
            return show

    def end(self, show_id: str, after: int) -> Show:
        """Close an endless show after the song at segment index `after`.

        What was made past that song is dropped, since the listener will not hear it,
        and the host's goodbye is written in its place. A show that is already closed is
        returned as it is.

        This is the only request that deletes a part of a show, so it is bounded (D044):
        it drops one break and one song at most. The player is never more than one part
        ahead of the listener, so a larger drop can only come from a bug.
        """
        with self._lock:
            show_dir = self._output_dir / show_id
            show = self._ready_endless_show(show_dir)
            if not show.is_open:
                return show
            if after >= len(show.segments) or show.segments[after].kind != "song":
                raise StepRefused(f"Segment {after} of show {show_id} is not a song.")
            dropped = show.segments[after + 1 :]
            songs_dropped = len([segment for segment in dropped if segment.kind == "song"])
            if songs_dropped > 1:
                raise StepRefused(
                    f"Show {show_id} has {songs_dropped} songs after segment {after}: "
                    "only the part made ahead can be dropped."
                )
            show.segments = show.segments[: after + 1]
            kept = {segment.track_id for segment in show.segments if segment.kind == "song"}
            show.tracks = [track for track in show.tracks if track.id in kept]
            self._generator.extend(show, show_dir, end=True)
            save_show(show, show_dir)
            # Only now: had the goodbye failed, show.json would still name these files.
            for segment in dropped:
                if segment.audio_file is None:
                    continue
                try:
                    (show_dir / segment.audio_file).unlink(missing_ok=True)
                except OSError as exc:
                    # Windows refuses to delete a file a player is still reading. The
                    # show is saved and closed: a leftover file does no harm.
                    log.warning(
                        "Could not delete %s of show %s: %s", segment.audio_file, show_id, exc
                    )
            return show

    def _ready_endless_show(self, show_dir: Path) -> Show:
        """Read show.json, or refuse: only a ready endless show takes a step.

        The callers hold the lock. A show is saved under that lock while it is generated
        or extended, so this read waits for the save and never meets a half-written file.
        """
        show = load_show(show_dir)
        if not show.config.endless:
            raise StepRefused(f"Show {show.id} is not an endless show.")
        if show.status == "failed":
            raise StepRefused(f"Show {show.id} is failed, not ready.")
        if show.status != "ready":
            raise StepRefused(f"Show {show.id} is {show.status}, not ready yet.")
        return show


def mark_stale_shows_failed(output_dir: Path) -> int:
    """Fail every show left in `pending` or `generating` by a previous run. Returns the count."""
    count = 0
    if not output_dir.is_dir():
        return count
    for show_dir in output_dir.iterdir():
        if not (show_dir / SHOW_FILE).is_file():
            continue
        try:
            show = load_show(show_dir)
        except ValueError:
            log.warning("Skipping unreadable %s", show_dir / SHOW_FILE)
            continue
        if show.status in ("pending", "generating"):
            show.status = "failed"
            show.error = RESTARTED_ERROR
            save_show(show, show_dir)
            count += 1
    return count
